/**
 * 정규식 메타문자 이스케이프 — 사용자·업스트림 문자열을 패턴에 끼워 넣기 전에 통과시킨다.
 *
 * 법령명·별표명·판례 키워드에는 `(제91조제1항관련)`처럼 괄호가 흔하고, 그대로 `new RegExp`에
 * 넣으면 캡처 그룹이 되어 매칭이 조용히 어긋난다. 사본이 셋(#144)이었고 전부 바이트 동일이라
 * 한 곳으로 모은다 — 이스케이프 문자 집합은 한 벌만 존재해야 한다.
 */
export function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
}
